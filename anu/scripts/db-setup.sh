#!/usr/bin/env bash
# Creates the ANU databases and applies migrations. Safe to re-run.
#
# 1. Uses the system PostgreSQL if the current OS user can connect over the
#    local socket with CREATEDB and CREATEROLE (peer auth), or ANU_DB_ADMIN_URL.
# 2. Otherwise starts a private cluster under anu/.data/pg (socket only, port
#    55432) with initdb and pg_ctl.
# 3. Writes anu/.env with generated secrets if it does not exist yet.
# 4. Applies migrations to the dev and test databases.
#
# Names can be overridden with ANU_DB_NAME and ANU_TEST_DB_NAME.
set -euo pipefail

ANU_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$HOME/.bun/bin:$PATH"
DB_NAME="${ANU_DB_NAME:-anu_platform}"
TEST_DB_NAME="${ANU_TEST_DB_NAME:-anu_platform_test}"
DB_USER="$(id -un)"
SYSTEM_SOCKET="${ANU_DB_SOCKET_DIR:-/var/run/postgresql}"
LOCAL_DIR="$ANU_DIR/.data/pg"
LOCAL_SOCKET="$ANU_DIR/.data/pg-socket"
LOCAL_PORT="${ANU_LOCAL_PG_PORT:-55432}"

pg_bin() {
  if command -v "$1" >/dev/null 2>&1 && [ "$1" != "initdb" ] && [ "$1" != "pg_ctl" ]; then
    command -v "$1"
    return
  fi
  local found
  found="$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)"
  if [ -n "$found" ] && [ -x "$found/$1" ]; then echo "$found/$1"; return; fi
  command -v "$1"
}
PSQL="$(pg_bin psql)"

can_admin() {
  "$PSQL" "$@" -d postgres -Atqc \
    "select (rolsuper or (rolcreatedb and rolcreaterole)) from pg_roles where rolname = current_user" \
    2>/dev/null | grep -qx t
}

if [ -n "${ANU_DB_ADMIN_URL:-}" ] && "$PSQL" "$ANU_DB_ADMIN_URL" -Atqc 'select 1' >/dev/null 2>&1; then
  echo "db-setup: using ANU_DB_ADMIN_URL"
  ADMIN=("$ANU_DB_ADMIN_URL")
  base_url() { echo "${ANU_DB_ADMIN_URL%/*}/$1"; }
elif can_admin -h "$SYSTEM_SOCKET" -p 5432; then
  echo "db-setup: using the system PostgreSQL as $DB_USER over $SYSTEM_SOCKET"
  ADMIN=(-h "$SYSTEM_SOCKET" -p 5432)
  base_url() { echo "postgres://$DB_USER@localhost:5432/$1?host=$SYSTEM_SOCKET"; }
else
  echo "db-setup: no admin access to the system PostgreSQL, using a private cluster in .data/pg"
  INITDB="$(pg_bin initdb)"
  PG_CTL="$(pg_bin pg_ctl)"
  mkdir -p "$LOCAL_SOCKET"
  chmod 700 "$LOCAL_SOCKET"
  if [ ! -f "$LOCAL_DIR/PG_VERSION" ]; then
    "$INITDB" -D "$LOCAL_DIR" -U "$DB_USER" -A peer --no-instructions >/dev/null
  fi
  if ! "$PG_CTL" -D "$LOCAL_DIR" status >/dev/null 2>&1; then
    "$PG_CTL" -D "$LOCAL_DIR" -l "$ANU_DIR/.data/pg.log" -w \
      -o "-p $LOCAL_PORT -k $LOCAL_SOCKET -c listen_addresses=''" start >/dev/null
  fi
  ADMIN=(-h "$LOCAL_SOCKET" -p "$LOCAL_PORT")
  base_url() { echo "postgres://$DB_USER@localhost:$LOCAL_PORT/$1?host=$LOCAL_SOCKET"; }
fi

for name in "$DB_NAME" "$TEST_DB_NAME"; do
  if [ "$("$PSQL" "${ADMIN[@]}" -d postgres -Atqc "select 1 from pg_database where datname = '$name'")" != "1" ]; then
    "$PSQL" "${ADMIN[@]}" -d postgres -qc "create database \"$name\""
    echo "db-setup: created database $name"
  fi
done

DATABASE_URL_VALUE="$(base_url "$DB_NAME")"
TEST_DATABASE_URL_VALUE="$(base_url "$TEST_DB_NAME")"

ENV_FILE="$ANU_DIR/.env"
if [ ! -f "$ENV_FILE" ]; then
  umask 077
  {
    echo "# Generated by scripts/db-setup.sh. Local only, never commit."
    echo "ANU_ENV=dev"
    echo "OTP_SENDER=dev"
    echo "DATABASE_URL=$DATABASE_URL_VALUE"
    echo "ANU_TEST_DATABASE_URL=$TEST_DATABASE_URL_VALUE"
    echo "ANU_OTP_SECRET=$(openssl rand -hex 32)"
    echo "ANU_INTERNAL_TOKEN=$(openssl rand -hex 32)"
    echo "ANU_SANDBOX_DRIVER=scripted"
    echo "KILO_BASE_URL=https://ai-gateway.kilo.ai/api/v1"
    echo "KILO_API_KEY=anonymous"
    echo "KILO_MODEL=kilo-auto/free"
  } > "$ENV_FILE"
  echo "db-setup: wrote $ENV_FILE with generated secrets"
else
  echo "db-setup: keeping existing $ENV_FILE"
fi

cd "$ANU_DIR"
DATABASE_URL="$DATABASE_URL_VALUE" bun scripts/db-migrate.ts
DATABASE_URL="$TEST_DATABASE_URL_VALUE" bun scripts/db-migrate.ts
echo "db-setup: done"
echo "  DATABASE_URL=$DATABASE_URL_VALUE"
echo "  ANU_TEST_DATABASE_URL=$TEST_DATABASE_URL_VALUE"
